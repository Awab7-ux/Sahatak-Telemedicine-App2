import { Asset } from 'expo-asset';
import * as FileSystem from 'expo-file-system';
import type { MedicalRecord } from '../types';

const BRAND_BLUE = '#0284c7';
const BRAND_DARK = '#0f172a';

let logoDataUriCache: string | null = null;

/**
 * Loads the Sahatak logo as a base64 data URI so it can be embedded
 * directly into the print HTML (works fully offline).
 */
export async function getLogoDataUri(): Promise<string> {
  if (logoDataUriCache) return logoDataUriCache;
  try {
    const asset = Asset.fromModule(require('../../assets/sahatak-logo.png'));
    if (!asset.downloaded) {
      await asset.downloadAsync();
    }
    const localUri = asset.localUri ?? asset.uri;
    const base64 = await FileSystem.readAsStringAsync(localUri, {
      encoding: FileSystem.EncodingType.Base64,
    });
    logoDataUriCache = `data:image/png;base64,${base64}`;
  } catch (e) {
    console.warn('Could not load Sahatak logo for PDF:', e);
    logoDataUriCache = '';
  }
  return logoDataUriCache;
}

const esc = (s: string | undefined | null): string =>
  (s ?? '')
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;');

interface ReportTexts {
  docTitle: string;
  patientLabel: string;
  doctorLabel: string;
  specialtyLabel: string;
  dateLabel: string;
  statusLabel: string;
  clinicLabel: string;
  summaryLabel: string;
  medicinesLabel: string;
  medicineHeaders: [string, string, string, string];
  footerNote: string;
  generatedBy: string;
}

